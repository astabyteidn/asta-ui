// Builds the `asta-ui` npm package's library half from the kit sources (no copies in this folder):
//   dist/index.js   every component, Radix build      import { Dialog } from "asta-ui"
//   dist/base.js    the same set, Base UI build        import { Dialog } from "asta-ui/base"
//   dist/<slug>.js  one component (Radix)              import { Dialog } from "asta-ui/dialog"
//   dist/base/<slug>.js                                import { Dialog } from "asta-ui/base/dialog"
//   dist/styles.css tokens + `@source` for Tailwind v4 @import "asta-ui/styles.css";
// Run from the repo root: bun packages/asta-ui/build.ts
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "tsup";
import { parseTokens, pointAtTokens, tokensCss } from "../../lib/ui-tokens";

const PKG = dirname(fileURLToPath(import.meta.url));
const ROOT = join(PKG, "../..");
const SRC = join(PKG, "src");
const DIST = join(PKG, "dist");
const read = (rel: string) => readFileSync(join(ROOT, rel), "utf8");

// ---- slug → source file (same registrations the site and registry use) ----
const files = new Map<string, string>();
for (const m of read("components/kit/demos.ts").matchAll(/"([a-z0-9-]+)":\s*load\(\(\) => import\("\.\/demos\//g))
  files.set(m[1], `components/kit/${m[1]}.tsx`);
for (const m of read("components/kit/variants.ts").matchAll(/"([a-z0-9-]+)":\s*load\(\(\) => import\("\.\/variants\/demos\//g))
  files.set(m[1], `components/kit/variants/${m[1]}.tsx`);
for (const m of read("components/lab/components.ts").matchAll(/"([a-z0-9-]+)":\s*load\(\(\) => import\("\.\/(blocks\/[A-Za-z0-9]+)"\)\)/g))
  files.set(m[1], `components/lab/${m[2]}.tsx`);

/** The Base UI twin when there is one (components/kit/base/…), else the shared file. */
const baseFile = (rel: string) => {
  const twin = rel.replace(/^components\/kit\//, "components/kit/base/");
  return rel.startsWith("components/kit/") && existsSync(join(ROOT, twin)) ? twin : rel;
};

const pascal = (slug: string) => slug.replace(/(^|-)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase());

interface Exports {
  values: string[];
  types: string[];
  /** Name of the default export when it is a declaration nobody else exports by name (lab blocks). */
  defaultName?: string;
}
function exportsOf(rel: string): Exports {
  const code = read(rel);
  const values: string[] = [];
  const types: string[] = [];
  for (const m of code.matchAll(/^export (?:declare )?(?:async )?(function|const|let|class|enum|type|interface) ([A-Za-z0-9_]+)/gm))
    (m[1] === "type" || m[1] === "interface" ? types : values).push(m[2]);
  const def = code.match(/^export default (?:async )?function ([A-Za-z0-9_]+)/m)?.[1];
  return { values, types, defaultName: def && !values.includes(def) ? def : undefined };
}

// ---- entry files (generated into src/, gitignored) ----
type Flavour = "radix" | "base";
const slugs = [...files.keys()];
const fileFor = (slug: string, f: Flavour) => (f === "base" ? baseFile(files.get(slug)!) : files.get(slug)!);
const spec = (from: string, rel: string) => {
  const r = relative(from, join(ROOT, rel)).replace(/\.tsx?$/, "");
  return r.startsWith(".") ? r : `./${r}`;
};

/** Names in the barrel, resolving clashes: the file whose slug matches the name keeps it, others get a prefix. */
function barrelNames(f: Flavour) {
  const owners = new Map<string, string[]>();
  const all = slugs.map((slug) => ({ slug, ex: exportsOf(fileFor(slug, f)) }));
  for (const { slug, ex } of all) for (const n of [...ex.values, ...ex.types]) owners.set(n, [...(owners.get(n) ?? []), slug]);
  const renamed: string[] = [];
  const nameFor = (slug: string, n: string) => {
    const o = owners.get(n)!;
    if (o.length < 2) return n;
    const keeper = o.find((s) => pascal(s) === n) ?? o[0];
    if (slug === keeper) return n;
    renamed.push(`${n} (${slug}) → ${pascal(slug)}${n}`);
    return `${pascal(slug)}${n}`;
  };
  return { all, nameFor, renamed };
}

function barrel(f: Flavour, dir: string) {
  const { all, nameFor, renamed } = barrelNames(f);
  const taken = new Set(all.flatMap(({ slug, ex }) => [...ex.values, ...ex.types].map((n) => nameFor(slug, n))));
  const lines = [`// Generated by packages/asta-ui/build.ts. Do not edit.`];
  for (const { slug, ex } of all) {
    const from = spec(dir, fileFor(slug, f));
    const v = ex.values.map((n) => (nameFor(slug, n) === n ? n : `${n} as ${nameFor(slug, n)}`));
    // Lab blocks and variants are default exports: export them by name, plus the slug's PascalCase
    // (e.g. TextareaAui003 for textarea-aui-003) so every component has a predictable name.
    const def: string[] = [];
    const isKitBase = files.get(slug)!.startsWith("components/kit/") && !files.get(slug)!.includes("/variants/");
    if (ex.defaultName && !taken.has(ex.defaultName)) {
      def.push(`default as ${ex.defaultName}`);
      taken.add(ex.defaultName);
    }
    if (!isKitBase && !taken.has(pascal(slug))) {
      def.push(`default as ${pascal(slug)}`);
      taken.add(pascal(slug));
    }
    if (v.length || def.length) lines.push(`export { ${[...v, ...def].join(", ")} } from "${from}";`);
    const t = ex.types.map((n) => (nameFor(slug, n) === n ? n : `${n} as ${nameFor(slug, n)}`));
    if (t.length) lines.push(`export type { ${t.join(", ")} } from "${from}";`);
  }
  return { code: lines.join("\n") + "\n", renamed };
}

rmSync(SRC, { recursive: true, force: true });
rmSync(DIST, { recursive: true, force: true });
mkdirSync(join(SRC, "base"), { recursive: true });

const entry: Record<string, string> = {};
const radix = barrel("radix", SRC);
const base = barrel("base", SRC);
writeFileSync(join(SRC, "index.ts"), radix.code);
writeFileSync(join(SRC, "base.ts"), base.code);
entry.index = join(SRC, "index.ts");
entry.base = join(SRC, "base.ts");
for (const slug of slugs) {
  for (const f of ["radix", "base"] as const) {
    const dir = f === "base" ? join(SRC, "base") : SRC;
    const from = spec(dir, fileFor(slug, f));
    const hasDefault = /^export default /m.test(read(fileFor(slug, f)));
    const out = join(dir, `${slug}.ts`);
    writeFileSync(out, `// Generated by packages/asta-ui/build.ts. Do not edit.\nexport * from "${from}";\n${hasDefault ? `export { default } from "${from}";\n` : ""}`);
    entry[f === "base" ? `base/${slug}` : slug] = out;
  }
}

// ---- bundle ----
const tokens = parseTokens(read("app/globals.css"));
// Run from the package folder: its package.json has "type": "module", so tsup writes .js and .d.ts.
process.chdir(PKG);
await build({
  entry,
  outDir: DIST,
  format: ["esm"],
  target: "es2020",
  platform: "browser",
  // Types come from one tsc run below. tsup's per-entry dts (rollup) needs 20+ GB for ~130 entries.
  dts: false,
  tsconfig: join(PKG, "tsconfig.build.json"),
  splitting: true,
  // esbuild already drops unused code per entry; tsup's rollup treeshake pass would strip the banner.
  treeshake: false,
  sourcemap: false,
  clean: false,
  minify: false,
  silent: true,
  external: ["react", "react-dom", "react/jsx-runtime", "radix-ui", /^@base-ui\/react/],
  // Every module is a client component (state, effects, pointer events). The banner restores the directive
  // esbuild strips from the sources, on entries and shared chunks alike.
  banner: { js: '"use client";' },
  esbuildOptions(o) {
    o.alias = { "@": ROOT };
    o.jsx = "automatic";
  },
  esbuildPlugins: [
    {
      name: "asta-tokens",
      setup(b) {
        // Same rewrite the shadcn registry applies, so inline var(--color-x) follows a nested `.dark`.
        b.onLoad({ filter: /components\/(kit|lab)\/.*\.tsx$/ }, (args) => ({
          contents: pointAtTokens(readFileSync(args.path, "utf8"), tokens),
          loader: "tsx",
        }));
      },
    },
  ],
});

// ---- types ----
// One tsc program emits .d.ts for every source under dist/types (mirroring the repo), then each entry
// gets a small .d.ts that re-exports from there. tsc leaves "@/..." aliases as is, so point them at dist/types.
const TYPES = join(DIST, "types");
execFileSync(join(ROOT, "node_modules/.bin/tsc"), ["-p", join(PKG, "tsconfig.types.json")], { stdio: "inherit" });
const walkDts = (dir: string): string[] =>
  readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walkDts(join(dir, e.name)) : e.name.endsWith(".d.ts") ? [join(dir, e.name)] : []));
for (const f of walkDts(TYPES)) {
  const src = readFileSync(f, "utf8");
  const out = src.replace(/(from |import\()"@\/([^"]+)"/g, (_, kw: string, rel: string) => {
    const r = relative(dirname(f), join(TYPES, rel));
    return `${kw}"${r.startsWith(".") ? r : `./${r}`}"`;
  });
  if (out !== src) writeFileSync(f, out);
}
const srcTypes = join(TYPES, relative(ROOT, SRC));
for (const name of Object.keys(entry)) {
  const target = relative(dirname(join(DIST, name)), join(srcTypes, name));
  const spec = target.startsWith(".") ? target : `./${target}`;
  const hasDefault = /^export \{ default \}/m.test(readFileSync(entry[name], "utf8"));
  mkdirSync(dirname(join(DIST, `${name}.d.ts`)), { recursive: true });
  writeFileSync(join(DIST, `${name}.d.ts`), `export * from "${spec}";\n${hasDefault ? `export { default } from "${spec}";\n` : ""}`);
}

// ---- styles.css ----
writeFileSync(
  join(DIST, "styles.css"),
  `/* Astabyte UI tokens. In your main stylesheet, after Tailwind:
 *   @import "tailwindcss";
 *   @import "asta-ui/styles.css";
 * The @source line below lets Tailwind v4 generate the classes the components use. */
@source "./";

${tokensCss(tokens)}`,
);

const kb = (n: number) => `${(n / 1024).toFixed(1)} kB`;
console.log(`asta-ui: ${slugs.length} components → dist (${Object.keys(entry).length} entries)`);
for (const r of new Set([...radix.renamed, ...base.renamed])) console.log(`  renamed in barrel: ${r}`);
console.log(`  index.js ${kb(readFileSync(join(DIST, "index.js")).length)}, styles.css ${kb(readFileSync(join(DIST, "styles.css")).length)}`);
