// Builds the Go + htmx package's assets and keeps their version in step with package.json:
//   go/ui/assets/asta.js   = src/core.js + every other src/*.js (one IIFE per component group)
//   go/ui/assets/asta.css  = Tailwind over the .templ files + src/core.css + every other src/*.css
//   bun run go          regenerate
//   bun run go --check  fail if anything is stale (CI)
// Tokens come from app/globals.css through lib/ui-tokens, the same values the registry and the npm package ship.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { parseTokens, tokensCss } from "../lib/ui-tokens";

const ROOT = process.cwd();
const UI = join(ROOT, "go/ui");
const ASSETS = join(UI, "assets");
const check = process.argv.includes("--check");
const read = (p: string) => readFileSync(p, "utf8");
const stale: string[] = [];

function put(path: string, content: string) {
  const cur = (() => {
    try {
      return read(path);
    } catch {
      return null;
    }
  })();
  if (cur === content) return;
  if (check) stale.push(path.replace(`${ROOT}/`, ""));
  else writeFileSync(path, content);
}

// ---- version ----
const { version } = JSON.parse(read(join(ROOT, "package.json")));
const goFile = join(UI, "ui.go");
put(goFile, read(goFile).replace(/const Version = "[^"]*"/, `const Version = "${version}"`));

// ---- script ----
const SRC = join(ASSETS, "src");
const parts = (ext: string) =>
  readdirSync(SRC)
    .filter((f) => f.endsWith(ext))
    .sort((a, b) => (a === `core${ext}` ? -1 : b === `core${ext}` ? 1 : a.localeCompare(b)));
const js = parts(".js")
  .map((f) => `/* ---- src/${f} ---- */\n${read(join(SRC, f)).trim()}\n`)
  .join("\n")
  .replace(/version: "[^"]*"/, `version: "${version}"`);
put(join(ASSETS, "asta.js"), `/* Generated by scripts/gen-go.ts from go/ui/assets/src. Do not edit. */\n${js}`);

// ---- stylesheet ----
const input = `/* Generated by scripts/gen-go.ts. Do not edit. */
@import "tailwindcss" source(none);
${parts(".css").map((f) => `@import "./src/${f}";`).join("\n")}

@source "../*.templ";
@source "../*.go";
@source "./src/*.js";
@source "../../examples/**/*.templ";

@custom-variant dark (&:is(.dark *));

${tokensCss(parseTokens(read(join(ROOT, "app/globals.css"))))}
@layer base {
  html {
    background: var(--paper);
    color: var(--ink);
    -webkit-font-smoothing: antialiased;
  }
  body {
    font-family: ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif;
  }
}
`;
put(join(ASSETS, "input.css"), input);

// Build from the committed input.css (its @import and @source paths are relative to it) into a temp file, then
// compare. In --check mode a stale input.css is already reported above.
const tmp = mkdtempSync(join(tmpdir(), "asta-go-"));
try {
  const out = join(tmp, "asta.css");
  execFileSync(join(ROOT, "node_modules/.bin/tailwindcss"), ["-i", join(ASSETS, "input.css"), "-o", out, "--minify"], { cwd: ROOT, stdio: ["ignore", "ignore", "inherit"] });
  put(join(ASSETS, "asta.css"), read(out));
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

if (stale.length) {
  console.error(`Stale Go package files (run \`bun run go\`):\n  ${stale.join("\n  ")}`);
  process.exit(1);
}
const kb = (readFileSync(join(ASSETS, "asta.css")).length / 1024).toFixed(1);
console.log(`go/ui: asta.css ${kb} kB, version ${version}${check ? " (checked)" : ""}`);
