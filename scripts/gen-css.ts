// Builds the CSS-only layer of the npm package (packages/asta-ui/css), for html/template, htmx, Rails, Django or
// plain HTML. No React, no templ.
//   css/src/*.css       hand-written sources: semantic classes (.asta-btn, .asta-input…) via @apply. Edit these.
//   css/tokens.css      generated: @theme + :root/.dark tokens (from app/globals.css) + every @keyframes of the
//                       Go runtime CSS (go/ui/assets/src/*.css)
//   css/components.css  generated: the Go runtime CSS minus its keyframes (dialog, toast, menu states…), then
//                       css/src/*.css wrapped in @layer components. It @source's ./asta.js, so a Tailwind build
//                       also gets the utilities the runtime puts in the markup it creates.
//   css/asta.js         generated: a copy of go/ui/assets/asta.js (run `bun run go` first)
//   css/asta.css        generated: tokens + components + preflight, built with the Tailwind CLI and minified
//   public/cdn/asta.{css,js}  copies for the temporary docs-site CDN (unversioned, always the current release)
//   bun run css          regenerate
//   bun run css --check  fail if anything is stale (CI)
// The class lists in css/src mirror the class strings in go/ui/*.templ, which mirror the React kit.
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseTokens, tokensCss } from "../lib/ui-tokens";

const ROOT = process.cwd();
const OUT = join(ROOT, "packages/asta-ui/css");
const SRC = join(OUT, "src");
const GO = join(ROOT, "go/ui/assets");
const check = process.argv.includes("--check");
const read = (p: string) => readFileSync(p, "utf8");
const stale: string[] = [];

function put(path: string, content: string) {
  let cur: string | null = null;
  try {
    cur = read(path);
  } catch {}
  if (cur === content) return;
  if (check) stale.push(path.replace(`${ROOT}/`, ""));
  else writeFileSync(path, content);
}

// Same order as gen-go.ts: core first, then the groups alphabetically.
const ordered = (dir: string, first: string) =>
  readdirSync(dir)
    .filter((f) => f.endsWith(".css"))
    .sort((a, b) => (a === first ? -1 : b === first ? 1 : a.localeCompare(b)));

// Split the Go runtime CSS into its @keyframes blocks and everything else.
function splitKeyframes(css: string) {
  const frames: string[] = [];
  let rest = "";
  let i = 0;
  for (;;) {
    const at = css.indexOf("@keyframes", i);
    if (at < 0) break;
    rest += css.slice(i, at);
    let depth = 0;
    let j = css.indexOf("{", at);
    for (; j < css.length; j++) {
      if (css[j] === "{") depth++;
      else if (css[j] === "}" && --depth === 0) break;
    }
    frames.push(css.slice(at, j + 1).trim());
    i = j + 1;
  }
  rest += css.slice(i);
  return { frames, rest: rest.replace(/\n{3,}/g, "\n\n").trim() };
}

const runtime = ordered(join(GO, "src"), "core.css").map((f) => ({ f, ...splitKeyframes(read(join(GO, "src", f))) }));
const HEAD = "/* Generated by scripts/gen-css.ts. Do not edit. */\n";

const tokens = `${HEAD}/* Astabyte UI tokens for Tailwind v4. Use with your own build:
 *   @import "tailwindcss";
 *   @import "asta-ui/css/tokens.css";
 *   @import "asta-ui/css/components.css";
 * Theme: override the variables below on :root, or put class="dark" on <html>. */

@custom-variant dark (&:is(.dark *));

${tokensCss(parseTokens(read(join(ROOT, "app/globals.css"))))}
@layer base {
  html {
    background: var(--paper);
    color: var(--ink);
    -webkit-font-smoothing: antialiased;
  }
  body {
    font-family: ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif;
  }
}

/* Keyframes the components and asta.js use. Transform and opacity only. */
${runtime.flatMap((r) => r.frames).join("\n")}
`;

const components = `${HEAD}/* Astabyte UI semantic classes (.asta-btn, .asta-input, .asta-dialog…). Import after tokens.css.
 * Sources: packages/asta-ui/css/src/*.css. Interactive parts are driven by asta.js through data-* and aria-*
 * attributes, so keep those in your markup. */

@source "./asta.js";

${runtime.map((r) => `/* ---- runtime: go/ui/assets/src/${r.f} ---- */\n${r.rest}\n`).join("\n")}
@layer components {
${ordered(SRC, "core.css")
  .map((f) => `/* ---- css/src/${f} ---- */\n${read(join(SRC, f)).trim()}\n`)
  .join("\n")}}
`;

const js = read(join(GO, "asta.js")).replace(/^\/\*.*?\*\/\n/, "/* Astabyte UI runtime. Generated by scripts/gen-css.ts from go/ui/assets/asta.js. Do not edit. */\n");

put(join(OUT, "tokens.css"), tokens);
put(join(OUT, "components.css"), components);
put(join(OUT, "asta.js"), js);
// Temporary CDN on the docs site (ui.astabyte.com/cdn/*): unversioned copies of the current release.
const CDN = join(ROOT, "public/cdn");
mkdirSync(CDN, { recursive: true });
put(join(CDN, "asta.js"), js);

// Build from fresh copies in a temp dir, so --check compares against what the sources produce now. The dir sits
// under node_modules so `@import "tailwindcss"` resolves.
mkdirSync(join(ROOT, "node_modules/.cache"), { recursive: true });
const tmp = mkdtempSync(join(ROOT, "node_modules/.cache/asta-css-"));
try {
  writeFileSync(join(tmp, "tokens.css"), tokens);
  writeFileSync(join(tmp, "components.css"), components);
  writeFileSync(join(tmp, "asta.js"), js);
  writeFileSync(join(tmp, "input.css"), `@import "tailwindcss" source(none);\n@import "./tokens.css";\n@import "./components.css";\n`);
  execFileSync(join(ROOT, "node_modules/.bin/tailwindcss"), ["-i", join(tmp, "input.css"), "-o", join(tmp, "asta.css"), "--minify"], {
    cwd: tmp,
    stdio: ["ignore", "ignore", "inherit"],
  });
  const css = `/* Astabyte UI ${JSON.parse(read(join(ROOT, "package.json"))).version} · MIT · https://github.com/astabyteidn/asta-ui */\n${read(join(tmp, "asta.css"))}`;
  put(join(OUT, "asta.css"), css);
  put(join(CDN, "asta.css"), css);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

if (stale.length) {
  console.error(`Stale CSS package files (run \`bun run css\`):\n  ${stale.join("\n  ")}`);
  process.exit(1);
}
const kb = (readFileSync(join(OUT, "asta.css")).length / 1024).toFixed(1);
console.log(`packages/asta-ui/css: asta.css ${kb} kB${check ? " (checked)" : ""}`);
