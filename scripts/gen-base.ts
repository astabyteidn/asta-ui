// Base UI twins: every kit file that uses Radix has a hand-written twin in components/kit/base/.
// This script fills in the rest of the Base UI tree so previews and the registry stay in step:
// components that only use Radix through another kit file (pricing → button) and demos are copied
// with their kit imports pointed at the base twins, and components/kit/base/demos.ts is written.
//   bun scripts/gen-base.ts          write
//   bun scripts/gen-base.ts --check  fail if anything is out of date (CI)
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

const KIT = "components/kit";
const BASE = `${KIT}/base`;
export const MARK = "// Generated by scripts/gen-base.ts";
const check = process.argv.includes("--check");

const list = (dir: string) => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".tsx")).sort().map((f) => `${dir}/${f}`) : []);
const sources = [...list(KIT), ...list(`${KIT}/variants`), ...list(`${KIT}/demos`), ...list(`${KIT}/variants/demos`)];
const code = new Map(sources.map((f) => [f, readFileSync(f, "utf8")]));
const twinOf = (f: string) => `${BASE}/${f.slice(KIT.length + 1)}`;
const handWritten = (f: string) => existsSync(twinOf(f)) && !readFileSync(twinOf(f), "utf8").startsWith(MARK);

const kitImports = (src: string) => [...src.matchAll(/from "@\/components\/kit\/((?:variants\/)?[a-z0-9-]+)"/g)].map((m) => `${KIT}/${m[1]}.tsx`);

// A file needs a Base UI version when it imports radix-ui, directly or through another kit file.
const memo = new Map<string, boolean>();
function radix(f: string): boolean {
  if (memo.has(f)) return memo.get(f)!;
  memo.set(f, false);
  const src = code.get(f) ?? "";
  const r = /from "radix-ui"/.test(src) || kitImports(src).some(radix);
  memo.set(f, r);
  return r;
}

const out = new Map<string, string>();
const rewrite = (src: string) =>
  src.replace(/from "@\/components\/kit\/((?:variants\/)?[a-z0-9-]+)"/g, (m, s: string) => (radix(`${KIT}/${s}.tsx`) ? `from "@/components/kit/base/${s}"` : m));

const missing: string[] = [];
for (const f of sources) {
  if (!radix(f) || handWritten(f)) continue;
  const src = code.get(f)!;
  if (/from "radix-ui"/.test(src)) {
    missing.push(f);
    continue;
  }
  out.set(twinOf(f), `${MARK} from ${f}. Do not edit.\n${rewrite(src)}`);
}
if (missing.length) {
  console.error(`These files import radix-ui but have no hand-written twin in ${BASE}/:\n  ${missing.join("\n  ")}`);
  process.exit(1);
}

// Preview registry: slug → Base UI demo, for every demo whose tree touches Radix.
const demos = sources.filter((f) => f.includes("/demos/") && radix(f));
const entries = demos.map((f) => {
  const slug = path.basename(f, ".tsx");
  const rel = f.slice(KIT.length + 1).replace(/\.tsx$/, "");
  return `  "${slug}": load(() => import("./${rel}")),`;
});
out.set(
  `${BASE}/demos.ts`,
  `${MARK}. Do not edit.
"use client";

import type { ComponentType } from "react";
import dynamic from "next/dynamic";

const load = (fn: () => Promise<{ default: ComponentType }>) => dynamic(fn, { ssr: false });

/** slug → the same demo built on the Base UI twins. Slugs missing here have no primitives (one version only). */
export const baseDemos: Record<string, ComponentType> = {
${entries.join("\n")}
};
`,
);

// Slugs with a Base UI build, for code that can't read the file tree (llms.txt, the skill generator, prompts).
out.set(
  "lib/base-slugs.ts",
  `${MARK}. Do not edit.
/** Items with a separate Base UI build (\`/r/base/<slug>.json\` differs from \`/r/<slug>.json\`). */
export const BASE_SLUGS: readonly string[] = ${JSON.stringify(sources.filter((f) => !f.includes("/demos/") && radix(f)).map((f) => path.basename(f, ".tsx")).sort(), null, 2)};
`,
);

// Write, or compare. Generated files that are no longer needed are removed.
const stale: string[] = [];
const walk = (dir: string): string[] =>
  existsSync(dir) ? readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0)).flatMap((e) => (e.isDirectory() ? walk(`${dir}/${e.name}`) : [`${dir}/${e.name}`])) : [];
for (const f of walk(BASE)) if (!out.has(f) && readFileSync(f, "utf8").startsWith(MARK)) stale.push(f);

let drift = 0;
for (const [f, content] of out) {
  const now = existsSync(f) ? readFileSync(f, "utf8") : null;
  if (now === content) continue;
  drift++;
  if (check) console.error(`out of date: ${f}`);
  else {
    mkdirSync(path.dirname(f), { recursive: true });
    writeFileSync(f, content);
  }
}
for (const f of stale) {
  drift++;
  if (check) console.error(`stale: ${f}`);
  else rmSync(f);
}
if (check && drift) {
  console.error("Run `bun run base` and commit the result.");
  process.exit(1);
}
console.log(`${check ? "checked" : "wrote"} ${out.size} generated files (${drift} changed), ${sources.filter(handWritten).length} hand-written twins`);
